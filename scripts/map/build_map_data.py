"""Regenerate the PA map data files used by the frontend.

Run from the repo root:  python scripts/map/build_map_data.py

Inputs
  - County polygons: U.S. Census-derived GeoJSON (plotly/datasets
    geojson-counties-fips.json), PA only.
  - Utility territories: HIFLD Electric Retail Service Territories, served by PASDA (Penn State).
  - Projects: scripts/map/data_centers.json, hand-edited. This is the source of truth for the
    data center list; edit it, then rerun this script.

Outputs (overwritten)
  - frontend/src/data/paGeo.ts         projected, simplified county and territory paths
  - frontend/src/data/dataCenters.ts   projects, each with its county and utility computed
                                       by point-in-polygon

Everything here is public geography and public reporting. No PJM Data Miner data is read or
written, which is why the public /map route may import these files (see ARCHITECTURE.md).
"""
import json
import math
import os
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(REPO, "frontend", "src", "data")

COUNTIES_URL = "https://raw.githubusercontent.com/plotly/datasets/master/geojson-counties-fips.json"
TERRITORY_LAYER = "https://mapservices.pasda.psu.edu/server/rest/services/pasda/HIFLD_FEMA_PA/MapServer/50"

# HIFLD name -> (id, display name, PJM zone name or None)
UTILS = {
    "PECO ENERGY CO": ("peco", "PECO Energy", "PECO"),
    "PPL ELECTRIC UTILITIES CORP": ("ppl", "PPL Electric Utilities", "PPL"),
    "METROPOLITAN EDISON CO": ("met-ed", "Met-Ed (Metropolitan Edison)", "METED"),
    "PENNSYLVANIA ELECTRIC CO": ("penelec", "Penelec (Pennsylvania Electric)", "PENELEC"),
    "DUQUESNE LIGHT CO": ("duquesne", "Duquesne Light", "DUQ"),
    "WEST PENN POWER COMPANY": ("west-penn", "West Penn Power", None),
    "PENNSYLVANIA POWER CO": ("penn-power", "Penn Power", None),
    "UGI UTILITIES, INC": ("ugi", "UGI Utilities", None),
    "CITIZENS ELECTRIC CO - (PA)": ("citizens", "Citizens' Electric", None),
    "WELLSBOROUGH ELECTRIC CO": ("wellsborough", "Wellsborough Electric", None),
}


GEO_HEADER = """\
// Generated by scripts/map/build_map_data.py. Do not edit by hand; regenerate instead.
// Counties: U.S. Census-derived county polygons (plotly/datasets geojson-counties-fips.json),
// PA only.
// Utility territories: HIFLD Electric Retail Service Territories, served by PASDA (Penn State).
// Both are public geography, not PJM Data Miner data, so this file is safe on public routes.
// Coordinates are projected to a 1000-unit-wide equirectangular viewBox and simplified.

export type ZoneName = "PECO" | "PPL" | "METED" | "PENELEC" | "DUQ";

"""

GEO_TYPES = """\

export interface PaCounty {
  fips: string;
  name: string;
  d: string;
  cx: number;
  cy: number;
}

export interface PaUtility {
  id: string;
  name: string;
  zone: ZoneName | null;
  customers: number;
  holding: string;
  d: string;
}

"""

DC_HEADER = """\
// Generated by scripts/map/build_map_data.py from scripts/map/data_centers.json.
// Edit the JSON, then rerun the script. Do not edit this file by hand.
//
// Curated from public reporting, one entry per project, each with the sources it was read from.
// This is NOT a complete registry: no authoritative public dataset exists yet. Locations are
// approximate (named site, or municipality), and the county and utility fields were computed
// by point-in-polygon against the geometry in paGeo.ts. Nothing here is PJM Data Miner data.

export interface DataCenterFigure {
  label: string;
  value: string;
  note: string;
}

export interface DataCenterSource {
  label: string;
  url: string;
}

export interface DataCenter {
  id: string;
  name: string;
  developer: string;
  place: string;
  /** "site": at or near a named site. "municipality": within the township, borough or city. */
  precision: "site" | "municipality";
  /** True once the project was denied or abandoned. */
  ended: boolean;
  county: string | null;
  countyFips: string | null;
  utilityId: string | null;
  x: number;
  y: number;
  lat: number;
  lon: number;
  status: string;
  asOf: string;
  summary: string;
  figures: DataCenterFigure[];
  sources: DataCenterSource[];
}

"""


def fetch_json(url):
    req = urllib.request.Request(url, headers={"User-Agent": "pa-grid-monitor-map-build/1.0"})
    return json.load(urllib.request.urlopen(req, timeout=120))


def polys(geom):
    return geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]


def main():
    counties = [f for f in fetch_json(COUNTIES_URL)["features"] if f["id"].startswith("42")]
    where = "NAME IN (" + ",".join("'" + n.replace("'", "''") + "'" for n in UTILS) + ")"
    query = urllib.parse.urlencode(
        {
            "where": where,
            "outFields": "NAME,CUSTOMERS,HOLDING_CO",
            "outSR": 4326,
            "maxAllowableOffset": 0.004,
            "geometryPrecision": 4,
            "f": "geojson",
        }
    )
    terr = fetch_json(f"{TERRITORY_LAYER}/query?{query}")["features"]
    projects = json.load(open(os.path.join(HERE, "data_centers.json"), encoding="utf8"))

    # ---- projection: equirectangular, scaled by cos of mid latitude, 1000 units wide ----
    lons = [pt[0] for f in counties for p in polys(f["geometry"]) for r in p for pt in r]
    lats = [pt[1] for f in counties for p in polys(f["geometry"]) for r in p for pt in r]
    lon0, lon1, lat0, lat1 = min(lons), max(lons), min(lats), max(lats)
    k = math.cos(math.radians((lat0 + lat1) / 2))
    W = 1000.0
    scale = W / ((lon1 - lon0) * k)
    H = round((lat1 - lat0) * scale, 1)

    def proj(lon, lat):
        return ((lon - lon0) * k * scale, (lat1 - lat) * scale)

    def dp(points, tol):
        if len(points) < 3:
            return points
        (x1, y1), (x2, y2) = points[0], points[-1]
        dx, dy = x2 - x1, y2 - y1
        norm = math.hypot(dx, dy) or 1e-12
        idx, dmax = 0, 0.0
        for i in range(1, len(points) - 1):
            d = abs(dy * points[i][0] - dx * points[i][1] + x2 * y1 - y2 * x1) / norm
            if d > dmax:
                idx, dmax = i, d
        if dmax > tol:
            return dp(points[: idx + 1], tol)[:-1] + dp(points[idx:], tol)
        return [points[0], points[-1]]

    def ring_path(ring, tol):
        pts = [proj(lon, lat) for lon, lat in ring]
        if len(pts) > 1 and pts[0] == pts[-1]:
            pts = pts[:-1]
        if len(pts) < 3:
            return ""
        # A closed ring has start == end, which makes Douglas-Peucker's reference line degenerate:
        # split at the point farthest from the start and simplify each half separately.
        far = max(
            range(len(pts)),
            key=lambda i: (pts[i][0] - pts[0][0]) ** 2 + (pts[i][1] - pts[0][1]) ** 2,
        )
        pts = dp(pts[: far + 1], tol)[:-1] + dp(pts[far:] + [pts[0]], tol)[:-1]
        if len(pts) < 3:
            return ""
        return "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z"

    def geom_path(geom, tol, bbox_filter=False):
        parts = []
        for p in polys(geom):
            if bbox_filter:
                xs = [pt[0] for pt in p[0]]
                ys = [pt[1] for pt in p[0]]
                outside = (
                    max(xs) < lon0 - 0.2
                    or min(xs) > lon1 + 0.2
                    or max(ys) < lat0 - 0.2
                    or min(ys) > lat1 + 0.2
                )
                if outside:
                    continue
            for r in p:
                s = ring_path(r, tol)
                if s:
                    parts.append(s)
        return "".join(parts)

    def inside(lon, lat, geom):
        hit = False
        for p in polys(geom):
            for ring in p:
                c = False
                j = len(ring) - 1
                for i in range(len(ring)):
                    xi, yi = ring[i][0], ring[i][1]
                    xj, yj = ring[j][0], ring[j][1]
                    crosses = (yi > lat) != (yj > lat)
                    x_at_lat = (xj - xi) * (lat - yi) / ((yj - yi) or 1e-12) + xi
                    if crosses and lon < x_at_lat:
                        c = not c
                    j = i
                if c:
                    hit = not hit
        return hit

    def centroid(geom):
        best, best_a = (0, 0), -1
        for p in polys(geom):
            pts = [proj(*pt[:2]) for pt in p[0]]
            a = cx = cy = 0.0
            for i in range(len(pts)):
                x0, y0 = pts[i]
                x1_, y1_ = pts[(i + 1) % len(pts)]
                cr = x0 * y1_ - x1_ * y0
                a += cr
                cx += (x0 + x1_) * cr
                cy += (y0 + y1_) * cr
            a *= 0.5
            if abs(a) > best_a and a != 0:
                best_a, best = abs(a), (cx / (6 * a), cy / (6 * a))
        return best

    county_rows = []
    for f in sorted(counties, key=lambda f: f["properties"]["NAME"]):
        cx, cy = centroid(f["geometry"])
        county_rows.append(
            {
                "fips": f["id"],
                "name": f["properties"]["NAME"],
                "d": geom_path(f["geometry"], 0.45),
                "cx": round(cx, 1),
                "cy": round(cy, 1),
            }
        )

    util_rows, util_geoms = [], {}
    for name in UTILS:
        f = next((x for x in terr if x["properties"]["NAME"] == name), None)
        if f is None:
            raise SystemExit(f"Utility not returned by the territory service: {name}")
        uid, label, zone = UTILS[name]
        util_geoms[uid] = f["geometry"]
        util_rows.append(
            {
                "id": uid,
                "name": label,
                "zone": zone,
                "customers": f["properties"]["CUSTOMERS"],
                "holding": f["properties"]["HOLDING_CO"],
                "d": geom_path(f["geometry"], 0.8, bbox_filter=True),
            }
        )

    dc_rows = []
    for p in projects["projects"]:
        county = next((f for f in counties if inside(p["lon"], p["lat"], f["geometry"])), None)
        utility = next(
            (uid for uid in util_geoms if inside(p["lon"], p["lat"], util_geoms[uid])), None
        )
        x, y = proj(p["lon"], p["lat"])
        county_name = county["properties"]["NAME"] if county else None
        print(f"{p['id']:22s} county={county_name!s:12s} utility={utility}")
        dc_rows.append(
            {
                "id": p["id"],
                "name": p["name"],
                "developer": p["developer"],
                "place": p["place"],
                "precision": p["precision"],
                "ended": p["ended"],
                "county": county_name,
                "countyFips": county["id"] if county else None,
                "utilityId": utility,
                "x": round(x, 1),
                "y": round(y, 1),
                "lat": p["lat"],
                "lon": p["lon"],
                "status": p["status"],
                "asOf": p["asOf"],
                "summary": p["summary"],
                "figures": p["figures"],
                "sources": p["sources"],
            }
        )

    os.makedirs(OUT, exist_ok=True)

    def js(value):
        return json.dumps(value, ensure_ascii=False)

    with open(os.path.join(OUT, "paGeo.ts"), "w", encoding="utf8", newline="\n") as fh:
        fh.write(GEO_HEADER)
        fh.write(f"export const PA_VIEWBOX = {{ w: {W:.0f}, h: {H} }};\n")
        fh.write(GEO_TYPES)
        fh.write(f"export const PA_COUNTIES: PaCounty[] = {js(county_rows)};\n\n")
        fh.write(f"export const PA_UTILITIES: PaUtility[] = {js(util_rows)};\n")

    with open(os.path.join(OUT, "dataCenters.ts"), "w", encoding="utf8", newline="\n") as fh:
        fh.write(DC_HEADER)
        fh.write(f'export const DATA_CENTERS_REVIEWED = "{projects["reviewed"]}";\n\n')
        fh.write(f"export const DATA_CENTERS: DataCenter[] = {js(dc_rows)};\n")

    print(
        f"viewBox {W:.0f} x {H}; counties {len(county_rows)}; "
        f"utilities {len(util_rows)}; projects {len(dc_rows)}"
    )

if __name__ == "__main__":
    main()
